#include <stdio.h>
#include <stdlib.h>

 int main () 

{   char n = '0', c = 'a';

    while (n <=  '9' )
        {putchar (n);
        n++;}


    while (c <= 'f')
        {putchar (c);
         c++;           }
         
    putchar ('\n');


  

    return 0;
}

